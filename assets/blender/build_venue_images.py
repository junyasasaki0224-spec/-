"""Run with Blender --background --factory-startup --python assets/blender/build_venue_images.py."""
import math
import random
from pathlib import Path

import bpy

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "roblox/assets/venue"
OUT.mkdir(parents=True, exist_ok=True)
KEYS = ".0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz"
palette = ["00000000"]


def color(hex_rgb):
    rgba = hex_rgb + "ff"
    if rgba not in palette:
        palette.append(rgba)
    return KEYS[palette.index(rgba)]


def image(w, h, pixel):
    return ["".join(pixel(x, y) for x in range(w)) for y in range(h)]


def crowd():
    rng = random.Random(2417)
    clothes = ["324e79", "d6b296", "b23f44", "488575", "edca65", "424953",
               "b1bfd8", "e8e1ce", "4a85ae", "bb7963"]
    skin = ["e6ba97", "cc9776", "9b6c56"]
    hair = ["443b39", "1e2a31", "6e6259"]
    rows = []
    for row in range(3):
        seats = []
        for i in range(52):
            inside = i % 13
            if (i < 3 or inside == 12 or rng.random() < .27):
                seats.append(None)
                continue
            seats.append((rng.choice(clothes), rng.choice(skin), rng.choice(hair),
                          rng.randrange(-2, 3), rng.randrange(4)))

        def pixel(x, y):
            seat = seats[x // 10]
            if seat is None:
                return "."
            shirt, face, cap, shift, style = seat
            dx, dy = x % 10 - 4.5, y - 7 - shift
            if (dx / 2.35) ** 2 + (dy / 3.0) ** 2 < 1:
                return color(cap if dy < -1 or (style == 1 and dx < -1) else face)
            if 3 <= dy < 13 and abs(dx) < min(4.6, 2.4 + (dy - 3) * .8):
                if dy > 9 and abs(dx) < 2 and style == 0:
                    return color(face)
                if abs(dx) > 3.65 or dy >= 12:
                    return color("485363")
                return color(shirt)
            return "."
        rows.extend(image(520, 22, pixel))
    return rows


def pane(x, y):
    # Contact shadow under the lintel, shaded jamb, reflected sky, glass seams and blinds.
    if x % 16 < 2 or y in (37, 38):
        return color("567185")
    if y < 4 or x % 16 == 2:
        return color("37485c")
    if y < 10:
        return color("516780")
    if (x + y // 2) % 53 < 6:
        return color("7993a5")
    if (x // 16) % 3 == 1 and y % 6 == 0:
        return color("8da0a6")
    return color("647f92" if y < 25 else "455c70")


def lamp(x, y):
    dx, dy = x % 12 - 5.5, y % 12 - 5.5
    r = math.hypot(dx, dy)
    if r < 2.5:
        return color("fff4ce")
    if r < 4:
        return color("e6d7ae")
    if r < 5:
        return color("aea69a")
    return color("58626a" if dy < 5 else "36454d")


maps = {"Crowd": crowd(), "Windows": image(64, 48, pane), "Lamps": image(72, 36, lamp)}
assert len(palette) <= len(KEYS)
source = ["-- Generated by assets/blender/build_venue_images.py. Rows run top to bottom.",
          "return {", '    palette = "' + "".join(palette) + '",',
          '    keys = "' + KEYS + '",']
for name, rows in maps.items():
    w, h = len(rows[0]), len(rows)
    pixels = []
    for line in reversed(rows):  # Blender image origin is bottom left
        for key in line:
            value = bytes.fromhex(palette[KEYS.index(key)])
            pixels.extend(c / 255 for c in value)
    img = bpy.data.images.new(name, width=w, height=h, alpha=True)
    img.colorspace_settings.name = "Non-Color"
    img.pixels.foreach_set(pixels)
    img.filepath_raw = str(OUT / (name + ".png"))
    img.file_format = "PNG"
    img.save()
    source.append("    " + name + " = {")
    source.extend('        "' + row + '",' for row in rows)
    source.append("    },")
source.append("}")
(ROOT / "roblox/src/VenuePixels.lua").write_text("\n".join(source) + "\n", encoding="utf-8", newline="\n")
